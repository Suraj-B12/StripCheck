"""Build the external literature-survey brief from the template and our verified .bib files.

Usage: python docs/prompts/build_brief.py
Writes docs/prompts/literature_survey_brief.md and docs/prompts/brief/*.txt (one paste-ready file per prompt).
"""
import pathlib, re

ROOT = pathlib.Path(__file__).resolve().parents[2]
HERE = ROOT / "docs" / "prompts"
NOTES = ROOT / "research_notes" / "StripCheck literature survey"


def bib_entries(path):
    """Return [(key, year, title)] from a .bib file, using brace matching for field values."""
    text = path.read_text(encoding="utf-8", errors="replace")
    out = []
    for m in re.finditer(r"@(\w+)\s*\{\s*([^,\s]+)\s*,", text):
        if m.group(1).lower() in ("comment", "string", "preamble"):
            continue
        body_start, depth, i = m.end(), 1, m.end()
        while i < len(text) and depth:
            depth += {"{": 1, "}": -1}.get(text[i], 0)
            i += 1
        body = text[body_start:i - 1]
        fields = {}
        for f in re.finditer(r"(\w+)\s*=\s*", body):
            j = f.end()
            if j < len(body) and body[j] == "{":
                d, k = 1, j + 1
                while k < len(body) and d:
                    d += {"{": 1, "}": -1}.get(body[k], 0)
                    k += 1
                val = body[j + 1:k - 1]
            else:
                val = re.match(r'"([^"]*)"|([^,\n]+)', body[j:]).group(0).strip('"')
            fields.setdefault(f.group(1).lower(), val)
        title = re.sub(r"[{}]", "", fields.get("title", "")).replace("\\&", "&")
        title = re.sub(r"\s+", " ", title).strip()
        out.append((m.group(2), re.sub(r"\D", "", fields.get("year", ""))[:4], title))
    return out


def known_list(theme):
    path = NOTES / f"{theme}.bib"
    entries = bib_entries(path) if path.exists() else []
    if not entries:
        return "- None yet."
    lines = []
    for key, year, title in sorted(entries, key=lambda e: e[0]):
        t = title if len(title) <= 120 else title[:117] + "..."
        lines.append(f"- `{key}` ({year or 'n.d.'}): {t}")
    return "\n".join(lines)


template = (HERE / "literature_survey_brief.template.md").read_text(encoding="utf-8")
brief = re.sub(r"\{\{KNOWN:(\w+)\}\}", lambda m: known_list(m.group(1)), template)
brief = brief.replace("*Version 1.0 · 26 October 2026 · prepared by the StripCheck team. Generated from `literature_survey_brief.template.md` by `build_brief.py`; edit the template, not this file.*",
                      "*Version 1.0 · 26 October 2026 · prepared by the StripCheck team. Generated by `build_brief.py` from `literature_survey_brief.template.md`; edit the template, not this file.*")
(HERE / "literature_survey_brief.md").write_text(brief, encoding="utf-8")

out_dir = HERE / "brief"
out_dir.mkdir(exist_ok=True)
master = re.search(r"<!-- BEGIN:MASTER -->\n(.*?)<!-- END:MASTER -->", brief, re.S).group(1).strip()
(out_dir / "00_MASTER_PROMPT.txt").write_text(master + "\n", encoding="utf-8")
cards = re.findall(r"<!-- BEGIN:CARD (T\d+) -->\n(.*?)<!-- END:CARD \1 -->", brief, re.S)
for cid, body in cards:
    key = re.search(r"THEME CARD T\d+ · (\w+)", body).group(1)
    (out_dir / f"{cid}_{key}.txt").write_text(body.strip() + "\n", encoding="utf-8")
total_known = sum(len(bib_entries(p)) for p in NOTES.glob("*.bib"))
print(f"wrote literature_survey_brief.md ({len(brief.split())} words), master prompt ({len(master.split())} words), "
      f"{len(cards)} theme cards; {total_known} verified references listed")
