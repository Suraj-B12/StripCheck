"""Merge the verified per-theme .bib files into paper/references.bib.

Usage: python paper/tools/merge_bib.py
Keeps the hand-verified entries already at the top of references.bib (above the MERGED marker), then appends every
entry from research_notes/StripCheck literature survey/*.bib, de-duplicated by key and by DOI. Prints a report.
"""
import pathlib, re

ROOT = pathlib.Path(__file__).resolve().parents[2]
NOTES = ROOT / "research_notes" / "StripCheck literature survey"
OUT = ROOT / "paper" / "references.bib"
MARKER = "% ===== MERGED FROM VERIFIED SURVEY NOTES (generated by paper/tools/merge_bib.py; do not edit below) ====="


def entries(text):
    """Yield (key, entry_text) using brace matching."""
    for m in re.finditer(r"@(\w+)\s*\{\s*([^,\s]+)\s*,", text):
        if m.group(1).lower() in ("comment", "string", "preamble"):
            continue
        depth, i = 1, m.end()
        while i < len(text) and depth:
            depth += {"{": 1, "}": -1}.get(text[i], 0)
            i += 1
        if depth == 0:
            yield m.group(2), text[m.start():i]


def doi_of(entry):
    m = re.search(r"\bdoi\s*=\s*[{\"]([^}\"]+)", entry, re.I)
    return m.group(1).strip().lower().removeprefix("https://doi.org/") if m else None


head = OUT.read_text(encoding="utf-8").split(MARKER)[0].rstrip() + "\n\n"
seen_keys = {k for k, _ in entries(head)}
seen_dois = {d: k for k, e in entries(head) if (d := doi_of(e))}
merged, dup_keys, dup_dois, per_file = [], [], [], {}
for bib in sorted(NOTES.glob("*.bib")):
    n = 0
    for key, entry in entries(bib.read_text(encoding="utf-8", errors="replace")):
        doi = doi_of(entry)
        if key in seen_keys:
            dup_keys.append(f"{key} ({bib.stem})")
            continue
        if doi and doi in seen_dois:
            dup_dois.append(f"{key} = {seen_dois[doi]} (doi {doi}, {bib.stem})")
            continue
        seen_keys.add(key)
        if doi:
            seen_dois[doi] = key
        merged.append(f"% theme: {bib.stem}\n{entry.strip()}\n")
        n += 1
    per_file[bib.stem] = n
OUT.write_text(head + MARKER + "\n\n" + "\n".join(merged), encoding="utf-8")
print(f"references.bib: {len(merged)} merged entries + {len(list(entries(head)))} hand-verified")
for k, v in per_file.items():
    print(f"  {k}: {v}")
print(f"duplicate keys skipped: {len(dup_keys)}")
for d in dup_keys:
    print(f"  {d}")
print(f"same DOI under another key (alias, skipped): {len(dup_dois)}")
for d in dup_dois:
    print(f"  {d}")
